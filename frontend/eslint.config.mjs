import { defineConfig, globalIgnores } from "eslint/config";
import nextVitals from "eslint-config-next/core-web-vitals";
import nextTs from "eslint-config-next/typescript";
import tseslint from "typescript-eslint";

// OpenSSF Best Practices Badge's warnings_strict criterion ("MUST be
// maximally strict with warnings, where practical"): typescript-eslint's own
// strict + stylistic type-checked tiers, layered after eslint-config-next's
// base rules (tsconfig.json already has "strict": true at the compiler
// level -- this is the linter-level equivalent). Narrowed below, not
// adopted wholesale -- see each override's own reasoning.
const eslintConfig = defineConfig([
  ...nextVitals,
  ...nextTs,
  ...tseslint.configs.strictTypeChecked,
  ...tseslint.configs.stylisticTypeChecked,
  {
    languageOptions: {
      parserOptions: {
        // allowDefaultProject: this file itself isn't covered by
        // tsconfig.json's own `include` (plain .ts/.tsx, not .mjs) --
        // without it, type-aware linting can't find a project for its own
        // config file and fails to parse it at all.
        projectService: { allowDefaultProject: ["eslint.config.mjs"] },
        tsconfigRootDir: import.meta.dirname,
      },
    },
  },
  {
    rules: {
      // This project's own established convention (every API client call,
      // every fetch()) is a plain `any`/unknown-cast boundary at the
      // network edge, validated by runtime shape checks and the
      // openapi-typescript-generated types just past that boundary, not by
      // banning `any` outright -- downgraded to a warning (still visible,
      // not silenced) rather than disabled, so a genuinely careless `any`
      // elsewhere still gets flagged for human judgment.
      "@typescript-eslint/no-explicit-any": "warn",
      // strictTypeChecked's own floating-promises/misused-promises rules
      // already catch the real bug class (an unawaited async call whose
      // rejection goes nowhere); no-unnecessary-condition flags a lot of
      // this project's own deliberate defensive checks against data that
      // *can* be null/undefined at runtime despite what a generated
      // OpenAPI type claims (an API response, not a value this project's
      // own code fully controls) -- not a real signal here.
      "@typescript-eslint/no-unnecessary-condition": "off",
      // Checked each hit individually, not assumed: every one is a plain
      // `${count}`/`${total}` number interpolation in a label string, never
      // an object that would stringify to "[object Object]" (the real bug
      // this rule exists to catch, still caught via no-base-to-string).
      "@typescript-eslint/restrict-template-expressions": [
        "error",
        { allowNumber: true, allowBoolean: true, allowNullish: true },
      ],
      // React's own idiom for a one-line event handler is exactly the
      // "returns void" arrow shorthand this rule otherwise forbids (e.g.
      // `onClick={() => setAudience("pm")}`) -- checked against every real
      // hit in this codebase (none were a genuine confusing-void mistake,
      // e.g. a ternary mixing a void and a real expression). This option
      // keeps the rule for that genuinely confusing shape while not fighting
      // the idiom this whole codebase is already written in.
      "@typescript-eslint/no-confusing-void-expression": ["error", { ignoreArrowShorthand: true }],
      // Pure style (object-shape `type` vs `interface` make no functional
      // difference without declaration merging, which this project doesn't
      // use) -- this codebase's own established convention is `type` for
      // every object shape already; enforcing `interface` would mean
      // rewriting working, already-reviewed declarations for a cosmetic
      // property, not fixing a real issue.
      "@typescript-eslint/consistent-type-definitions": "off",
    },
  },
  {
    // lib/api-types.ts is auto-generated by openapi-typescript (see its own
    // header comment: "Do not make direct changes to the file") -- not
    // hand-authored, same reasoning markdownlint.yml already applies to
    // frontend/AGENTS.md. Confirmed this is the only source of every
    // consistent-indexed-object-style hit in the whole project (41/41).
    ignores: ["lib/api-types.ts"],
  },
  {
    // Test files mock async interfaces (Response.json()/text(), DOM/BOM
    // globals like matchMedia) and drive Playwright's own callback-heavy
    // API -- a different risk class from application code, same "tests/**"
    // exception this project's own backend ruff config already draws for
    // the equivalent rule classes (false-positive security/strictness
    // findings on deliberate test-fixture shapes, not real application bugs).
    files: ["**/*.test.{ts,tsx}", "**/*.spec.ts", "vitest.setup.ts", "tests/e2e/**"],
    rules: {
      // Mocking `Response.json()`/`.text()` (both real async methods) and
      // Playwright fixtures/hooks routinely has nothing to await inside.
      "@typescript-eslint/require-await": "off",
      // DOM/BOM mock stubs (matchMedia's addListener/removeListener, etc.)
      // and Playwright's own `() => {}` no-op handlers are empty by design.
      "@typescript-eslint/no-empty-function": "off",
      // Test code routinely asserts a DOM query result is non-null
      // (`page.locator(...).first()!`) where the test's own prior assertion
      // already established that -- a different risk tolerance than
      // application code, where non-null assertions stay flagged.
      "@typescript-eslint/no-non-null-assertion": "off",
      // Tests intentionally exercise untyped JSON (API fixtures, generated
      // SBOM output) without re-declaring full response types for every
      // fixture -- real `any`-propagation risk in application code stays
      // flagged.
      "@typescript-eslint/no-unsafe-assignment": "off",
      "@typescript-eslint/no-unsafe-member-access": "off",
      "@typescript-eslint/no-unsafe-call": "off",
    },
  },
  // Override default ignores of eslint-config-next.
  globalIgnores([
    // Default ignores of eslint-config-next:
    ".next/**",
    "out/**",
    "build/**",
    "coverage/**",
    "next-env.d.ts",
  ]),
]);

export default eslintConfig;
