from datetime import UTC, datetime

from app.analyzer.facts import ModuleFacts
from app.analyzer.readme import render_readme_markdown
from app.analyzer.schemas import ConfigOption, Feature, Integration, ModuleDoc, Risk, Tag


def _bare_facts(**overrides) -> ModuleFacts:
    defaults = {
        "name": "Vendor_Module", "composer_name": None, "composer_type": None,
        "license": None, "enabled": None, "setup_version": None,
    }
    defaults.update(overrides)
    return ModuleFacts(**defaults)


def _bare_doc(**overrides) -> ModuleDoc:
    defaults = {
        "summary": "A summary.",
        "description": "A description.",
        "confidence": 0.9,
        "pm_text": "PM text.",
        "dev_text": "Dev text.",
    }
    defaults.update(overrides)
    return ModuleDoc(**defaults)


UPDATED_AT = datetime(2026, 1, 1, tzinfo=UTC)


def test_renders_the_minimal_shape_with_every_optional_section_omitted():
    markdown = render_readme_markdown(
        "Vendor_Module", _bare_doc(), _bare_facts(), "anthropic/claude-haiku-5-5", "v1", "abc123456789", UPDATED_AT
    )

    assert markdown.startswith("# Vendor_Module\n")
    assert "## Features" not in markdown
    assert "## Integrations" not in markdown
    assert "## Tags" not in markdown
    assert "## Configuration" not in markdown
    assert "## Risks" not in markdown
    assert "## Dependencies" not in markdown
    assert "## Plugins" not in markdown
    assert "## Observers" not in markdown
    assert "## For PMs" in markdown and "PM text." in markdown
    assert "## For developers" in markdown and "Dev text." in markdown
    assert "_Generated by Claude (anthropic/claude-haiku-5-5) · prompt v1 · content hash `abc123456789` · " in markdown


def test_title_includes_the_composer_name_when_known():
    markdown = render_readme_markdown(
        "Vendor_Module",
        _bare_doc(),
        _bare_facts(composer_name="vendor/module"),
        "m", "v1", "hash", UPDATED_AT,
    )
    assert markdown.startswith("# Vendor_Module (`vendor/module`)\n")


def test_renders_every_optional_section_when_populated():
    doc = _bare_doc(
        features=[Feature(name="Credit check", description="Blocks checkout.", source="Plugin.php")],
        integrations=[
            Integration(name="Klaviyo", description="Sends events.", source="Observer.php"),
            Integration(name="No-source integration", description="Unclear source."),
        ],
        tags=[Tag(name="payments", source="parser", confidence=1.0)],
        config_options=[
            ConfigOption(path="section/group/field", label="Enabled"),
            ConfigOption(path="section/group/unlabeled"),
        ],
        risks=[Risk(description="Hardcoded secret found.", severity="high")],
    )
    facts = _bare_facts(
        dependencies=["Magento_Sales"],
        di_plugins=[("Magento\\Sales\\Model\\Order", "SamplePlugin", "Vendor\\Module\\Plugin\\SamplePlugin")],
        event_observers=[("sales_order_save_after", "SampleObserver", "Vendor\\Module\\Observer\\SampleObserver")],
    )

    markdown = render_readme_markdown("Vendor_Module", doc, facts, "m", "v1", "hash", UPDATED_AT)

    assert "- **Credit check**: Blocks checkout. _(source: Plugin.php)_" in markdown
    assert "- **Klaviyo**: Sends events. _(source: Observer.php)_" in markdown
    assert "- **No-source integration**: Unclear source." in markdown
    assert "`payments`" in markdown
    assert "- `section/group/field` — Enabled" in markdown
    assert "- `section/group/unlabeled`" in markdown
    assert "- **[high]** Hardcoded secret found." in markdown
    assert "- Magento_Sales" in markdown
    assert "- `SamplePlugin` intercepts `Magento\\Sales\\Model\\Order` via `Vendor\\Module\\Plugin\\SamplePlugin`" in markdown
    assert (
        "- `SampleObserver` listens for `sales_order_save_after` via `Vendor\\Module\\Observer\\SampleObserver`"
        in markdown
    )
