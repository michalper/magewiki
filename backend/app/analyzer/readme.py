from datetime import datetime

from app.analyzer.facts import ModuleFacts
from app.analyzer.schemas import ModuleDoc


def render_readme_markdown(
    module_name: str,
    doc: ModuleDoc,
    facts: ModuleFacts,
    model: str,
    prompt_version: str,
    content_hash: str,
    updated_at: datetime,
) -> str:
    lines: list[str] = []
    title = module_name if not facts.composer_name else f"{module_name} (`{facts.composer_name}`)"
    lines.append(f"# {title}")
    lines.append("")
    lines.append(doc.summary)
    lines.append("")
    lines.append("## Description")
    lines.append("")
    lines.append(doc.description)

    if doc.features:
        lines.append("")
        lines.append("## Features")
        lines.append("")
        for f in doc.features:
            lines.append(f"- **{f.name}**: {f.description} _(source: {f.source})_")

    if doc.integrations:
        lines.append("")
        lines.append("## Integrations")
        lines.append("")
        for i in doc.integrations:
            suffix = f" _(source: {i.source})_" if i.source else ""
            lines.append(f"- **{i.name}**: {i.description}{suffix}")

    if doc.tags:
        lines.append("")
        lines.append("## Tags")
        lines.append("")
        lines.append(", ".join(f"`{t.name}`" for t in doc.tags))

    if doc.config_options:
        lines.append("")
        lines.append("## Configuration")
        lines.append("")
        for c in doc.config_options:
            lines.append(f"- `{c.path}`" + (f" — {c.label}" if c.label else ""))

    if doc.risks:
        lines.append("")
        lines.append("## Risks")
        lines.append("")
        for r in doc.risks:
            lines.append(f"- **[{r.severity}]** {r.description}")

    lines.append("")
    lines.append("## For PMs")
    lines.append("")
    lines.append(doc.pm_text)
    lines.append("")
    lines.append("## For developers")
    lines.append("")
    lines.append(doc.dev_text)

    # Parser-truth facts, rendered directly from the database, never from the AI doc.
    if facts.dependencies:
        lines.append("")
        lines.append("## Dependencies")
        lines.append("")
        lines.extend(f"- {d}" for d in facts.dependencies)

    if facts.di_plugins:
        lines.append("")
        lines.append("## Plugins")
        lines.append("")
        lines.extend(
            f"- `{name}` intercepts `{intercepted}` via `{plugin_class}`"
            for intercepted, name, plugin_class in facts.di_plugins
        )

    if facts.event_observers:
        lines.append("")
        lines.append("## Observers")
        lines.append("")
        lines.extend(
            f"- `{name}` listens for `{event}` via `{observer_class}`"
            for event, name, observer_class in facts.event_observers
        )

    lines.append("")
    lines.append("---")
    lines.append(
        f"_Generated by Claude ({model}) · prompt {prompt_version} · "
        f"content hash `{content_hash[:12]}` · last analyzed {updated_at.isoformat()}_"
    )

    return "\n".join(lines)
